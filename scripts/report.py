"""Regenerate the results section of README.md from eval/results/latest.json.

Every number in the README comes from here; nothing is typed by hand.
Standard library only, so it runs on the host: `make report`.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LATEST = ROOT / "eval" / "results" / "latest.json"
README = ROOT / "README.md"
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
MODE_NAMES = {"bm25": "BM25 only", "dense": "Dense only (bge-small)", "hybrid": "Hybrid (RRF)",
              "hybrid_rerank": "Hybrid + cross-encoder rerank"}


def pct(x) -> str:
    return "—" if x is None else f"{100 * x:.1f}%"


def num(x, fmt="{:.3f}") -> str:
    return "—" if x is None else fmt.format(x)


def render(r: dict) -> str:
    c, g, cfg = r["corpus"], r["golden"], r["config"]
    a = r.get("answers") or {}
    note = r.get("answers_note")
    ja = r.get("judge_agreement")
    head = r["retrieval"]["headline"]
    unverified = g["questions"] - g["verified"]

    lines = [
        f"_Generated by `make report` from `eval/results/latest.json` "
        f"(suite `{r['suite']}`, {r['generated_at']}{', commit ' + r['git_sha'] if r.get('git_sha') else ''})._",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Corpus | {c['documents']} postmortems / {c['chunks']} chunks ({c.get('companies', '—')} companies) |",
        f"| Golden set | {g['questions']} questions ({g['unanswerable']} unanswerable, {g['cross_document']} cross-document) |",
        f"| Golden items human-verified | {g['verified']} / {g['questions']} |",
        f"| Recall@5 (doc, hybrid + rerank) | {pct(head['recall@5'])} |",
        f"| Recall@10 (doc, hybrid + rerank) | {pct(head['recall@10'])} |",
        f"| MRR@10 | {num(head['mrr@10'])} |",
        f"| Faithfulness (LLM judge, mean per answer) | {pct(a.get('faithfulness')) if a else '— ' + (note or '')} |",
        f"| Citation coverage (cited factual sentences) | {pct(a.get('citation_coverage')) if a else '—'} |",
        f"| Abstention accuracy (unanswerable) | {pct(a.get('abstention_accuracy')) if a else '—'} |",
        f"| False abstention (answerable) | {pct(a.get('false_abstention_rate')) if a else '—'} |",
        f"| Latency p50 / p95 (end to end) | {num(a.get('latency_ms_p50'), '{:.0f}')} / {num(a.get('latency_ms_p95'), '{:.0f}')} ms |" if a else "| Latency p50 / p95 | — |",
        f"| Cost per question ({cfg['claude_model']}) | {num(a.get('cost_usd_per_question'), '${:.4f}')} |" if a else "| Cost per question | — |",
        f"| Judge–human agreement | {pct(ja['agreement'])} on {ja['claims']} claims / {ja['answers']} answers (κ = {num(ja['cohen_kappa'], '{:.2f}')}) |"
        if ja else "| Judge–human agreement | not measured yet (`make judge-sample`, label, `make judge-score`) |",
        "",
        "**Retrieval ablation** (same questions, same first-stage candidates):",
        "",
        "| Retriever | Recall@5 | Recall@10 | MRR@10 | Evidence Recall@5 |",
        "|---|---|---|---|---|",
    ]
    for mode, m in r["retrieval"]["ablation"].items():
        lines.append(f"| {MODE_NAMES.get(mode, mode)} | {pct(m['recall@5'])} | {pct(m['recall@10'])} | "
                     f"{num(m['mrr@10'])} | {pct(m['evidence_recall@5'])} |")
    lines += [
        "",
        f"Config: `TOP_K_BM25={cfg['top_k_bm25']}`, `TOP_K_DENSE={cfg['top_k_dense']}`, "
        f"`FUSED_K={cfg['fused_k']}`, `RERANK_K={cfg['rerank_k']}`, `RRF_K={cfg['rrf_k']}`, "
        f"`RERANK_THRESHOLD={cfg['rerank_threshold']}`, chunks ≈{cfg['chunk_tokens']} tokens "
        f"/ {cfg['chunk_overlap_tokens']} overlap, generator `{cfg['claude_model']}` (effort `{cfg['effort']}`), "
        f"judge `{cfg['judge_model']}`.",
    ]
    if unverified:
        lines += ["", f"> ⚠️ {unverified} golden items are LLM-drafted and not yet human-verified "
                      "(`make verify-golden`). Treat the numbers as provisional until this reads 0."]
    if not a:
        lines += ["", f"> Answer-quality metrics were not computed in this run: {note}."]
    return "\n".join(lines)


def main() -> int:
    if not LATEST.exists():
        print(f"{LATEST} not found: run `make eval` first", file=sys.stderr)
        return 1
    result = json.loads(LATEST.read_text())
    block = f"{START}\n{render(result)}\n{END}"
    readme = README.read_text()
    if START not in readme:
        print("README has no results markers", file=sys.stderr)
        return 1
    README.write_text(re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, readme, flags=re.S))
    print(f"README results updated from {LATEST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
